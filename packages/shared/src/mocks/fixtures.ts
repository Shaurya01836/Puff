/** Steps for a mock session, one minute apart, so the Activity tab has something to show in the browser. */
function steps(
  sessionId: string,
  taskId: string,
  list: Array<[ActivityStep['kind'], string, boolean?]>,
): ActivityStep[] {
  return list.map(([kind, text, ok], i) => ({
    id: `${sessionId}:${i}`,
    taskId,
    sessionId,
    at: min(30) + i * 20_000,
    kind,
    text,
    ...(ok === undefined ? {} : { ok }),
  }));
}

